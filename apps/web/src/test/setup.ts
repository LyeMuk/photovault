// jsdom doesn't implement matchMedia; main.tsx and Settings.tsx call it to pick the
// initial theme, so tests need a stub or they'd throw before rendering anything.
if (!window.matchMedia) {
  window.matchMedia = (query: string) =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addListener: () => {},
      removeListener: () => {},
      addEventListener: () => {},
      removeEventListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList;
}
